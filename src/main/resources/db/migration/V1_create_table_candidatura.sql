CREATE TABLE candidatura (
id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
empresa          VARCHAR(150) NOT NULL,
cargo            VARCHAR(150) NOT NULL,
link_vaga        VARCHAR(500),
modalidade       VARCHAR(20),
origem           VARCHAR(50),
data_candidatura DATE         NOT NULL,
status           VARCHAR(20)  NOT NULL,
observacoes      TEXT
criado_em        TIMESTAMP    NOT NULL,
atualizado_em    TIMESTAMP    NOT NULL,

CONSTRAINT ck_candidatura_status CHECK (
        status IN ('ENVIADA', 'EM_ANALISE', 'ENTREVISTA', 'OFERTA', 'RECUSADA', 'DESISTIU')
    ),
CONSTRAINT ck_candidatura_modalidade CHECK (
        modalidade IS NULL OR modalidade IN ('REMOTO', 'HIBRIDO', 'PRESENCIAL')
    )
);